import AppKit

/// One representation of a pasteboard item.
public struct PasteboardEntry: Sendable, Equatable {
    public let type: String
    public let data: Data
    public init(type: String, data: Data) {
        self.type = type
        self.data = data
    }
}

/// A full in-memory copy of the pasteboard: every item, every type in the item's own order
/// (readers pick the first type they understand, so order matters), as raw data.
/// Never written to disk.
public struct PasteboardSnapshot: Sendable, Equatable {
    public let items: [[PasteboardEntry]]
    public init(items: [[PasteboardEntry]]) { self.items = items }
    public var isEmpty: Bool { items.isEmpty }

    /// Content a password manager or similar marked as concealed or transient. Restoring it
    /// would republish it under a new change count, defeating auto-clear timers.
    public var isConcealed: Bool {
        items.contains { $0.contains { $0.type == PasteboardMarkers.concealed || $0.type == PasteboardMarkers.transient } }
    }
}

/// Why the clipboard cannot be borrowed safely. In every case nothing has been written yet.
public enum ClipboardUnavailable: Error, Equatable, Sendable {
    /// The user denied this app clipboard access (macOS 15.4+ Paste from Other Apps setting).
    case accessDenied
    /// Some data could not be read (access prompt declined, or promised data from an app that
    /// quit), so the contents could not be put back faithfully.
    case unreadable
    /// More data than we are willing to copy into memory.
    case tooLarge
    /// The clipboard changed while it was being saved.
    case changedWhileSaving
    /// The clipboard holds concealed/transient content (e.g. a password).
    case sensitiveContent
}

/// Handle for a string we placed on the pasteboard. `wasRead` turns true once some app has
/// asked for the data, which is how we know a synthetic paste actually happened.
public protocol PasteWriteHandle: AnyObject, Sendable {
    var wasRead: Bool { get }
}

@MainActor
public protocol PasteboardAccessing: AnyObject {
    var changeCount: Int { get }
    /// Reads every item and type. Throws instead of returning a partial copy.
    func snapshot() throws(ClipboardUnavailable) -> PasteboardSnapshot
    func restore(_ snapshot: PasteboardSnapshot)
    func readString() -> String?
    func data(forType type: String) -> Data?
    /// Writes `text` lazily (data is produced on first request) and marks it transient and
    /// concealed so well-behaved clipboard managers do not record it.
    func writeTransientString(_ text: String) -> PasteWriteHandle
}

/// Markers from nspasteboard.org honored by most clipboard history tools.
public enum PasteboardMarkers {
    public static let transient = "org.nspasteboard.TransientType"
    public static let concealed = "org.nspasteboard.ConcealedType"
    public static let autoGenerated = "org.nspasteboard.AutoGeneratedType"
}

@MainActor
public final class SystemPasteboard: PasteboardAccessing {
    private let pasteboard: NSPasteboard

    public init(_ pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
    }

    public var changeCount: Int { pasteboard.changeCount }

    /// Upper bound for a snapshot held in memory. Larger clipboards (big images) make the
    /// clipboard fallback refuse rather than stall and balloon memory.
    public static let maxSnapshotBytes = 32 * 1024 * 1024

    public func snapshot() throws(ClipboardUnavailable) -> PasteboardSnapshot {
        if #available(macOS 15.4, *), pasteboard.accessBehavior == .alwaysDeny {
            throw .accessDenied
        }
        var items: [[PasteboardEntry]] = []
        var total = 0
        for item in pasteboard.pasteboardItems ?? [] {
            var entries: [PasteboardEntry] = []
            for type in item.types {
                // A missing representation means we could not put the clipboard back as it
                // was; better not to touch it at all.
                guard let data = item.data(forType: type) else { throw .unreadable }
                total += data.count
                guard total <= Self.maxSnapshotBytes else { throw .tooLarge }
                entries.append(PasteboardEntry(type: type.rawValue, data: data))
            }
            if !entries.isEmpty { items.append(entries) }
        }
        return PasteboardSnapshot(items: items)
    }

    public func restore(_ snapshot: PasteboardSnapshot) {
        // Host-only: content the user already had is put back locally and not pushed to
        // other devices through Universal Clipboard a second time.
        pasteboard.prepareForNewContents(with: .currentHostOnly)
        guard !snapshot.isEmpty else { return }
        let items = snapshot.items.map { entries -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for entry in entries { item.setData(entry.data, forType: NSPasteboard.PasteboardType(entry.type)) }
            return item
        }
        pasteboard.writeObjects(items)
    }

    public func readString() -> String? {
        pasteboard.string(forType: .string)
    }

    public func data(forType type: String) -> Data? {
        pasteboard.data(forType: NSPasteboard.PasteboardType(type))
    }

    public func writeTransientString(_ text: String) -> PasteWriteHandle {
        let provider = LazyStringProvider(text)
        let item = NSPasteboardItem()
        item.setDataProvider(provider, forTypes: [.string])
        item.setData(Data(), forType: NSPasteboard.PasteboardType(PasteboardMarkers.transient))
        item.setData(Data(), forType: NSPasteboard.PasteboardType(PasteboardMarkers.concealed))
        item.setData(Data(), forType: NSPasteboard.PasteboardType(PasteboardMarkers.autoGenerated))
        // Host-only so the converted text never travels to other devices.
        pasteboard.prepareForNewContents(with: .currentHostOnly)
        pasteboard.writeObjects([item])
        return provider
    }
}

/// Supplies the string only when asked, recording that the request happened.
/// AppKit may call the provider off the main thread, so state is guarded by a lock.
final class LazyStringProvider: NSObject, NSPasteboardItemDataProvider, PasteWriteHandle, @unchecked Sendable {
    private let lock = NSLock()
    private var text: String?
    private var read = false

    init(_ text: String) { self.text = text }

    var wasRead: Bool { lock.withLock { read } }

    func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
        guard let text = lock.withLock({ self.text }) else { return }
        item.setString(text, forType: type)
        lock.withLock { read = true }
    }

    func pasteboardFinishedWithDataProvider(_ pasteboard: NSPasteboard) {
        // Drop our copy of the text as soon as the pasteboard no longer needs it.
        lock.withLock { text = nil }
    }
}
